"""Manual, rubric-agnostic Official OJT Evaluation persistence.

Official evaluation data is entered by the supervisor and remains separate from
attendance, Daily Performance, Work scores, Logbook reviews, and ML outputs.
No rubric criteria, weights, or official score are generated by Nexora.
"""
from datetime import datetime
from decimal import Decimal, InvalidOperation

from app.Models.db import get_db_connection, using_postgres


MAX_EVALUATION_ITEMS = 50
MAX_CRITERION_NAME_LENGTH = 200
MAX_ITEM_COMMENT_LENGTH = 2000
MAX_REMARKS_LENGTH = 5000


def _value(row, key, index=0, default=None):
    if row is None:
        return default
    try:
        if key in row.keys():
            value = row[key]
            return default if value is None else value
    except AttributeError:
        pass
    try:
        value = row[index]
        return default if value is None else value
    except (IndexError, KeyError, TypeError):
        return default


def _display_name(row):
    first_name = str(_value(row, "first_name", 3, "") or "").strip()
    middle_name = str(_value(row, "middle_name", 4, "") or "").strip()
    last_name = str(_value(row, "last_name", 5, "") or "").strip()
    username = str(_value(row, "username", 1, "") or "").strip()
    parts = [part for part in (first_name, middle_name, last_name) if part]
    return " ".join(parts) if parts else username or "Intern"


def _decimal(value, label, *, required=True, positive=False, nonnegative=False):
    text = "" if value is None else str(value).strip()
    if not text:
        if required:
            raise ValueError(f"{label} is required.")
        return None
    try:
        number = Decimal(text)
    except (InvalidOperation, TypeError, ValueError):
        raise ValueError(f"{label} must be a valid number.")
    if not number.is_finite():
        raise ValueError(f"{label} must be a finite number.")
    if positive and number <= 0:
        raise ValueError(f"{label} must be greater than zero.")
    if nonnegative and number < 0:
        raise ValueError(f"{label} cannot be negative.")
    return number


def ensure_ojt_evaluation_schema():
    """Create the additive official-evaluation tables for Postgres and SQLite."""
    conn = get_db_connection()
    try:
        if using_postgres():
            conn.execute(
                """
                CREATE TABLE IF NOT EXISTS ojt_evaluations (
                    id SERIAL PRIMARY KEY,
                    classroom_id INTEGER NOT NULL REFERENCES classrooms(id) ON DELETE CASCADE,
                    student_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
                    supervisor_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
                    status TEXT NOT NULL DEFAULT 'draft',
                    overall_score NUMERIC(12,4),
                    remarks TEXT,
                    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
                    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
                    submitted_at TIMESTAMP,
                    UNIQUE(classroom_id, student_id)
                )
                """
            )
            conn.execute(
                """
                CREATE TABLE IF NOT EXISTS ojt_evaluation_items (
                    id SERIAL PRIMARY KEY,
                    evaluation_id INTEGER NOT NULL REFERENCES ojt_evaluations(id) ON DELETE CASCADE,
                    criterion_name TEXT NOT NULL,
                    rating_value NUMERIC(12,4) NOT NULL,
                    max_value NUMERIC(12,4) NOT NULL,
                    weight NUMERIC(12,4),
                    comments TEXT,
                    sort_order INTEGER NOT NULL DEFAULT 0
                )
                """
            )
        else:
            conn.execute(
                """
                CREATE TABLE IF NOT EXISTS ojt_evaluations (
                    id INTEGER PRIMARY KEY AUTOINCREMENT,
                    classroom_id INTEGER NOT NULL REFERENCES classrooms(id) ON DELETE CASCADE,
                    student_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
                    supervisor_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
                    status TEXT NOT NULL DEFAULT 'draft',
                    overall_score REAL,
                    remarks TEXT,
                    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
                    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
                    submitted_at TIMESTAMP,
                    UNIQUE(classroom_id, student_id)
                )
                """
            )
            conn.execute(
                """
                CREATE TABLE IF NOT EXISTS ojt_evaluation_items (
                    id INTEGER PRIMARY KEY AUTOINCREMENT,
                    evaluation_id INTEGER NOT NULL REFERENCES ojt_evaluations(id) ON DELETE CASCADE,
                    criterion_name TEXT NOT NULL,
                    rating_value REAL NOT NULL,
                    max_value REAL NOT NULL,
                    weight REAL,
                    comments TEXT,
                    sort_order INTEGER NOT NULL DEFAULT 0
                )
                """
            )

        conn.execute(
            "CREATE INDEX IF NOT EXISTS idx_ojt_evaluations_supervisor_class ON ojt_evaluations(supervisor_id, classroom_id)"
        )
        conn.execute(
            "CREATE INDEX IF NOT EXISTS idx_ojt_evaluations_student ON ojt_evaluations(student_id, classroom_id)"
        )
        conn.execute(
            "CREATE INDEX IF NOT EXISTS idx_ojt_evaluation_items_evaluation ON ojt_evaluation_items(evaluation_id, sort_order)"
        )
        conn.commit()
    except Exception:
        try:
            conn.rollback()
        except Exception:
            pass
        raise
    finally:
        conn.close()


def _evaluation_dict(row):
    if not row:
        return None
    overall = _value(row, "overall_score", 5, None)
    return {
        "id": int(_value(row, "id", 0, 0) or 0),
        "classroom_id": int(_value(row, "classroom_id", 1, 0) or 0),
        "student_id": int(_value(row, "student_id", 2, 0) or 0),
        "supervisor_id": int(_value(row, "supervisor_id", 3, 0) or 0),
        "status": str(_value(row, "status", 4, "draft") or "draft"),
        "overall_score": float(overall) if overall is not None else None,
        "remarks": _value(row, "remarks", 6, "") or "",
        "created_at": _value(row, "created_at", 7, None),
        "updated_at": _value(row, "updated_at", 8, None),
        "submitted_at": _value(row, "submitted_at", 9, None),
    }


def _item_dict(row):
    weight = _value(row, "weight", 4, None)
    return {
        "id": int(_value(row, "id", 0, 0) or 0),
        "criterion_name": _value(row, "criterion_name", 1, "") or "",
        "rating_value": float(_value(row, "rating_value", 2, 0) or 0),
        "max_value": float(_value(row, "max_value", 3, 0) or 0),
        "weight": float(weight) if weight is not None else None,
        "comments": _value(row, "comments", 5, "") or "",
        "sort_order": int(_value(row, "sort_order", 6, 0) or 0),
    }


def get_supervisor_evaluation_context(supervisor_id, classroom_id, student_id=None):
    """Return one owned classroom and the selected intern's official evaluation."""
    try:
        supervisor_id = int(supervisor_id)
        classroom_id = int(classroom_id)
        student_id = int(student_id) if student_id not in (None, "") else None
    except (TypeError, ValueError):
        return {"ok": False, "status_code": 404}

    conn = get_db_connection()
    try:
        classroom = conn.execute(
            """
            SELECT c.id, c.name, c.section, c.description, c.code, c.archived,
                   COALESCE(cid.company_name, '') AS company_name,
                   COALESCE(cid.internship_title, '') AS internship_title
            FROM classrooms c
            LEFT JOIN classroom_internship_details cid ON cid.classroom_id = c.id
            WHERE c.id = ? AND c.supervisor_id = ?
            LIMIT 1
            """,
            (classroom_id, supervisor_id),
        ).fetchone()
        if not classroom:
            exists = conn.execute(
                "SELECT 1 FROM classrooms WHERE id = ? LIMIT 1",
                (classroom_id,),
            ).fetchone()
            return {"ok": False, "status_code": 403 if exists else 404}

        student_rows = conn.execute(
            """
            SELECT u.id, u.username, u.email,
                   COALESCE(sp.first_name, '') AS first_name,
                   COALESCE(sp.middle_name, '') AS middle_name,
                   COALESCE(sp.last_name, '') AS last_name,
                   COALESCE(sp.student_id, '') AS student_number,
                   COALESCE(sp.major_program, '') AS major_program,
                   COALESCE(sp.grade_year, '') AS grade_year
            FROM classroom_students cs
            JOIN users u ON u.id = cs.student_id
            LEFT JOIN student_profiles sp ON sp.user_id = u.id
            WHERE cs.classroom_id = ?
            ORDER BY LOWER(COALESCE(NULLIF(sp.first_name, ''), u.username)),
                     LOWER(COALESCE(NULLIF(sp.last_name, ''), u.email)),
                     u.id
            """,
            (classroom_id,),
        ).fetchall()

        students = []
        for row in student_rows:
            students.append(
                {
                    "id": int(_value(row, "id", 0, 0) or 0),
                    "username": _value(row, "username", 1, "") or "",
                    "email": _value(row, "email", 2, "") or "",
                    "display_name": _display_name(row),
                    "student_number": _value(row, "student_number", 6, "") or "",
                    "major_program": _value(row, "major_program", 7, "") or "",
                    "grade_year": _value(row, "grade_year", 8, "") or "",
                }
            )

        selected_student = None
        if students:
            if student_id is None:
                selected_student = students[0]
            else:
                selected_student = next(
                    (student for student in students if student["id"] == student_id),
                    None,
                )
                if selected_student is None:
                    return {"ok": False, "status_code": 404}

        evaluation = None
        items = []
        if selected_student:
            row = conn.execute(
                """
                SELECT id, classroom_id, student_id, supervisor_id, status,
                       overall_score, remarks, created_at, updated_at, submitted_at
                FROM ojt_evaluations
                WHERE classroom_id = ? AND student_id = ? AND supervisor_id = ?
                LIMIT 1
                """,
                (classroom_id, selected_student["id"], supervisor_id),
            ).fetchone()
            evaluation = _evaluation_dict(row)
            if evaluation:
                item_rows = conn.execute(
                    """
                    SELECT id, criterion_name, rating_value, max_value, weight, comments, sort_order
                    FROM ojt_evaluation_items
                    WHERE evaluation_id = ?
                    ORDER BY sort_order, id
                    """,
                    (evaluation["id"],),
                ).fetchall()
                items = [_item_dict(item) for item in item_rows]

        return {
            "ok": True,
            "status_code": 200,
            "classroom": {
                "id": int(_value(classroom, "id", 0, 0) or 0),
                "name": _value(classroom, "name", 1, "") or "Intern Classroom",
                "section": _value(classroom, "section", 2, "") or "",
                "description": _value(classroom, "description", 3, "") or "",
                "code": _value(classroom, "code", 4, "") or "",
                "archived": bool(_value(classroom, "archived", 5, 0)),
                "company_name": _value(classroom, "company_name", 6, "") or "",
                "internship_title": _value(classroom, "internship_title", 7, "") or "",
            },
            "students": students,
            "selected_student": selected_student,
            "evaluation": evaluation,
            "items": items,
        }
    finally:
        conn.close()


def _normalize_items(items, status):
    normalized = []
    raw_items = list(items or [])
    if len(raw_items) > MAX_EVALUATION_ITEMS:
        raise ValueError(f"Official evaluation is limited to {MAX_EVALUATION_ITEMS} criteria.")

    for index, item in enumerate(raw_items):
        name = str(item.get("criterion_name") or "").strip()
        rating_text = str(item.get("rating_value") or "").strip()
        max_text = str(item.get("max_value") or "").strip()
        weight_text = str(item.get("weight") or "").strip()
        comments = str(item.get("comments") or "").strip()

        is_blank = not any((name, rating_text, max_text, weight_text, comments))
        if is_blank:
            continue
        if not name:
            raise ValueError(f"Criterion {index + 1} needs a name.")
        if len(name) > MAX_CRITERION_NAME_LENGTH:
            raise ValueError(
                f"Criterion names must be {MAX_CRITERION_NAME_LENGTH} characters or fewer."
            )
        if len(comments) > MAX_ITEM_COMMENT_LENGTH:
            raise ValueError(
                f"Criterion comments must be {MAX_ITEM_COMMENT_LENGTH:,} characters or fewer."
            )

        rating = _decimal(rating_text, f"Rating for {name}", nonnegative=True)
        maximum = _decimal(max_text, f"Maximum value for {name}", positive=True)
        if rating > maximum:
            raise ValueError(f"Rating for {name} cannot exceed its maximum value.")
        weight = _decimal(
            weight_text,
            f"Weight for {name}",
            required=False,
            nonnegative=True,
        )
        normalized.append(
            {
                "criterion_name": name,
                "rating_value": float(rating),
                "max_value": float(maximum),
                "weight": float(weight) if weight is not None else None,
                "comments": comments,
                "sort_order": len(normalized),
            }
        )

    if status == "submitted" and not normalized:
        raise ValueError("Add at least one official evaluation criterion before submitting.")
    return normalized


def save_supervisor_ojt_evaluation(
    supervisor_id,
    classroom_id,
    student_id,
    status,
    items,
    overall_score=None,
    remarks="",
):
    """Atomically save a draft or submit one manual official evaluation."""
    try:
        supervisor_id = int(supervisor_id)
        classroom_id = int(classroom_id)
        student_id = int(student_id)
    except (TypeError, ValueError):
        return {"ok": False, "error": "Invalid intern or Intern Classroom."}

    status = str(status or "").strip().lower()
    if status not in {"draft", "submitted"}:
        return {"ok": False, "error": "Invalid evaluation status."}

    remarks = str(remarks or "").strip()
    if len(remarks) > MAX_REMARKS_LENGTH:
        return {
            "ok": False,
            "error": f"Overall remarks must be {MAX_REMARKS_LENGTH:,} characters or fewer.",
        }

    try:
        normalized_overall = _decimal(
            overall_score,
            "Overall score",
            required=False,
            nonnegative=True,
        )
        normalized_items = _normalize_items(items, status)
    except ValueError as exc:
        return {"ok": False, "error": str(exc)}

    conn = get_db_connection()
    try:
        allowed = conn.execute(
            """
            SELECT 1
            FROM classrooms c
            JOIN classroom_students cs ON cs.classroom_id = c.id
            WHERE c.id = ? AND c.supervisor_id = ? AND cs.student_id = ?
            LIMIT 1
            """,
            (classroom_id, supervisor_id, student_id),
        ).fetchone()
        if not allowed:
            return {"ok": False, "error": "Intern is not enrolled in this Intern Classroom."}

        existing = conn.execute(
            """
            SELECT id, status
            FROM ojt_evaluations
            WHERE classroom_id = ? AND student_id = ?
            LIMIT 1
            """,
            (classroom_id, student_id),
        ).fetchone()
        if existing and str(_value(existing, "status", 1, "draft") or "draft") == "submitted":
            return {
                "ok": False,
                "error": "Reopen the submitted Official OJT Evaluation before editing it.",
            }

        now = datetime.now()
        submitted_at = now if status == "submitted" else None
        if existing:
            evaluation_id = int(_value(existing, "id", 0, 0) or 0)
            conn.execute(
                """
                UPDATE ojt_evaluations
                SET supervisor_id = ?, status = ?, overall_score = ?, remarks = ?,
                    updated_at = ?, submitted_at = ?
                WHERE id = ? AND classroom_id = ? AND student_id = ?
                """,
                (
                    supervisor_id,
                    status,
                    float(normalized_overall) if normalized_overall is not None else None,
                    remarks or None,
                    now,
                    submitted_at,
                    evaluation_id,
                    classroom_id,
                    student_id,
                ),
            )
        else:
            conn.execute(
                """
                INSERT INTO ojt_evaluations (
                    classroom_id, student_id, supervisor_id, status,
                    overall_score, remarks, created_at, updated_at, submitted_at
                ) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?)
                """,
                (
                    classroom_id,
                    student_id,
                    supervisor_id,
                    status,
                    float(normalized_overall) if normalized_overall is not None else None,
                    remarks or None,
                    now,
                    now,
                    submitted_at,
                ),
            )
            row = conn.execute(
                """
                SELECT id FROM ojt_evaluations
                WHERE classroom_id = ? AND student_id = ?
                LIMIT 1
                """,
                (classroom_id, student_id),
            ).fetchone()
            evaluation_id = int(_value(row, "id", 0, 0) or 0)

        conn.execute(
            "DELETE FROM ojt_evaluation_items WHERE evaluation_id = ?",
            (evaluation_id,),
        )
        for item in normalized_items:
            conn.execute(
                """
                INSERT INTO ojt_evaluation_items (
                    evaluation_id, criterion_name, rating_value, max_value,
                    weight, comments, sort_order
                ) VALUES (?, ?, ?, ?, ?, ?, ?)
                """,
                (
                    evaluation_id,
                    item["criterion_name"],
                    item["rating_value"],
                    item["max_value"],
                    item["weight"],
                    item["comments"] or None,
                    item["sort_order"],
                ),
            )

        conn.commit()
        return {
            "ok": True,
            "error": None,
            "evaluation_id": evaluation_id,
            "classroom_id": classroom_id,
            "student_id": student_id,
            "status": status,
            "item_count": len(normalized_items),
        }
    except Exception:
        try:
            conn.rollback()
        except Exception:
            pass
        raise
    finally:
        conn.close()


def reopen_supervisor_ojt_evaluation(supervisor_id, classroom_id, student_id):
    """Explicitly return a submitted evaluation to draft before corrections."""
    try:
        supervisor_id = int(supervisor_id)
        classroom_id = int(classroom_id)
        student_id = int(student_id)
    except (TypeError, ValueError):
        return {"ok": False, "error": "Invalid intern or Intern Classroom."}

    conn = get_db_connection()
    try:
        row = conn.execute(
            """
            SELECT oe.id, oe.status
            FROM ojt_evaluations oe
            JOIN classrooms c ON c.id = oe.classroom_id
            JOIN classroom_students cs
              ON cs.classroom_id = oe.classroom_id AND cs.student_id = oe.student_id
            WHERE oe.classroom_id = ?
              AND oe.student_id = ?
              AND oe.supervisor_id = ?
              AND c.supervisor_id = ?
            LIMIT 1
            """,
            (classroom_id, student_id, supervisor_id, supervisor_id),
        ).fetchone()
        if not row:
            return {"ok": False, "error": "Official OJT Evaluation was not found."}
        if str(_value(row, "status", 1, "draft") or "draft") != "submitted":
            return {"ok": False, "error": "Only a submitted evaluation can be reopened."}

        conn.execute(
            """
            UPDATE ojt_evaluations
            SET status = 'draft', submitted_at = NULL, updated_at = ?
            WHERE id = ?
            """,
            (datetime.now(), int(_value(row, "id", 0, 0) or 0)),
        )
        conn.commit()
        return {"ok": True, "error": None}
    except Exception:
        try:
            conn.rollback()
        except Exception:
            pass
        raise
    finally:
        conn.close()
